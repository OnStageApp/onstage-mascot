// Writes packages/web/src/spec-data.ts (everything) and static-data.ts (states only, for the static entry)
// from spec/. Generated; never edit the output by hand.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

export function genWebData() {
  const spec = p => JSON.parse(fs.readFileSync(path.join(ROOT, 'spec', p), 'utf8'));
  const mdir = path.join(ROOT, 'spec', 'motion');
  const motion = {};
  for (const f of fs.readdirSync(mdir).sort()) if (f.endsWith('.json')) motion[f.slice(0, -5)] = spec('motion/' + f);
  const data = { palette: spec('palette.json'), states: spec('states.json'), motion };
  const src = '// Generated by tools/gen-web-data.mjs from spec/. Do not edit: change spec/ and run `npm run bake`.\n'
    + "import type { SpecData } from './types.js';\n\n"
    // JSON.parse of a string literal is faster to load than an object literal of this size.
    + `export const SPEC: SpecData = JSON.parse(${JSON.stringify(JSON.stringify(data))});\n`;
  fs.writeFileSync(path.join(ROOT, 'packages', 'web', 'src', 'spec-data.ts'), src);

  // The static entry gets the palette, canvas, ground and the states without their `motion` reference:
  // no clip, no idle or blink settings, nothing the player needs. Only what drawing a resting pose reads.
  const { palette, states } = data;
  const staticData = {
    palette,
    canvas: states.canvas,
    ground: states.ground,
    states: states.states.map(({ motion, ...rest }) => rest),
  };
  const staticSrc = '// Generated by tools/gen-web-data.mjs from spec/. Do not edit: change spec/ and run `npm run bake`.\n'
    + '// States only: no motion clips, no idle or blink settings. The static entry (static.ts) imports this and not spec-data.ts.\n'
    + "import type { StaticSpecData } from './types.js';\n\n"
    + `export const STATIC_SPEC: StaticSpecData = JSON.parse(${JSON.stringify(JSON.stringify(staticData))});\n`;
  fs.writeFileSync(path.join(ROOT, 'packages', 'web', 'src', 'static-data.ts'), staticSrc);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) genWebData();
