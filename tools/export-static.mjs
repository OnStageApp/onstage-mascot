// npm run export-static
// Writes the resting pose of every state as files, for emails, marketing, Framer and sticker packs:
//   assets/svg/<key>.svg        light surface, vector
//   assets/svg-dark/<key>.svg   dark surface (no ground shadow)
//   assets/png/<key>.png        480 px, transparent background, light surface
//   assets/png/<key>@1x.png     240 px
//   assets/index.json           key, group, name, use note and file paths for every state
// The SVG comes from the static entry (packages/web/dist/static.js, the same renderRestSvg an app
// calls); the PNG is that SVG rasterised by rsvg-convert. Needs `npm run build` first.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ROOT, RSVG } from './lib/web.mjs';

export const ASSETS = path.join(ROOT, 'assets');
export const PNG_SIZE = 480;
/** The width and height written into the SVG files: the 240 unit canvas, so a file opens at its natural size. */
export const SVG_SIZE = 240;

export async function loadStatic() {
  const entry = path.join(ROOT, 'packages', 'web', 'dist', 'static.js');
  if (!fs.existsSync(entry)) throw new Error('packages/web/dist is missing: run `npm run build`');
  return import(pathToFileURL(entry).href);
}

/** Everything the export writes except the PNGs, in memory: { 'svg/hello.svg': '<svg...', 'index.json': '...' }. */
export async function buildTextAssets() {
  const { STATE_INFO, renderRestSvg } = await loadStatic();
  const files = {};
  const states = STATE_INFO.map(({ key, group, name, use }) => {
    files[`svg/${key}.svg`] = renderRestSvg(key, { surface: 'light', size: SVG_SIZE }) + '\n';
    files[`svg-dark/${key}.svg`] = renderRestSvg(key, { surface: 'dark', size: SVG_SIZE }) + '\n';
    return { key, group, name, use, svg: `svg/${key}.svg`, svgDark: `svg-dark/${key}.svg`, png: `png/${key}.png`, png1x: `png/${key}@1x.png` };
  });
  files['index.json'] = JSON.stringify({
    format: 1,
    note: 'Generated by `npm run export-static` from the static entry. Resting pose of every state. Paths are relative to this folder. SVG: vector, 240 unit canvas (scales freely). PNG: transparent background, light surface, 480 px (png) and 240 px (png1x).',
    sizes: { svg: SVG_SIZE, png: PNG_SIZE, png1x: PNG_SIZE / 2 },
    states,
  }, null, 1) + '\n';
  return files;
}

export function rasterise(svg, file, px) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  execFileSync(RSVG, ['-w', String(px), '-h', String(px), '-o', file], { input: svg });
}

export async function exportStatic(dir = ASSETS) {
  const text = await buildTextAssets();
  fs.rmSync(dir, { recursive: true, force: true });
  for (const [rel, body] of Object.entries(text)) {
    fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true });
    fs.writeFileSync(path.join(dir, rel), body);
  }
  const index = JSON.parse(text['index.json']);
  for (const s of index.states) {
    const svg = text[s.svg];
    rasterise(svg, path.join(dir, s.png), PNG_SIZE);
    rasterise(svg, path.join(dir, s.png1x), PNG_SIZE / 2);
  }
  return index;
}

export function dirSize(dir) {
  let total = 0;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    total += e.isDirectory() ? dirSize(p) : fs.statSync(p).size;
  }
  return total;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const index = await exportStatic();
  const kb = n => (n / 1024).toFixed(1) + ' KB';
  const size = sub => dirSize(path.join(ASSETS, sub));
  console.log(`wrote ${index.states.length} states to ${path.relative(ROOT, ASSETS)}/`);
  console.log(`  svg ${kb(size('svg'))}, svg-dark ${kb(size('svg-dark'))}, png (480 and @1x) ${kb(size('png'))}, index.json ${kb(fs.statSync(path.join(ASSETS, 'index.json')).size)}`);
  console.log(`  total ${kb(dirSize(ASSETS))}`);
}
