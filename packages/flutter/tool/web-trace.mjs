// Records what the web player does frame by frame, so test/player_trace_test.dart can check that
// the Flutter player makes the same random() calls on the same frames and blinks the same way.
// Writes test/fixtures/web_player_trace.json. Rerun after changing spec/ (npm run build first):
//   node packages/flutter/tool/web-trace.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadWeb } from '../../../tools/lib/web.mjs';

const web = await loadWeb();
const here = path.dirname(fileURLToPath(import.meta.url));

// A fixed, irregular dt sequence: normal frames, a dropped frame, a zero dt and long gaps (clamped).
const irregular = n => Array.from({ length: n }, (_, i) => [1 / 60, 1 / 60, 1 / 30, 0, 1 / 120, 0.25, 1 / 60, 0.07][i % 8]);
const steady = n => Array.from({ length: n }, () => 1 / 60);

const scenarios = [
  { name: 'hello-seed7', state: 'hello', play: true, seed: 7, dts: steady(900) },
  { name: 'idle-seed1-irregular', state: 'idle', play: false, seed: 1, dts: irregular(900) },
  { name: 'loading-seed42', state: 'loading', play: true, seed: 42, dts: steady(900) },
  { name: 'welcome-team-seed3', state: 'welcome-team', play: true, seed: 3, dts: irregular(700) },
];

// Eye heights of every oval eye in the frame, in draw order (they carry the blink factor).
const ovalRy = svg => [...svg.matchAll(/<ellipse [^>]*rx="5\.2" ry="([\d.]+)"/g)].map(m => +m[1]);

const out = [];
for (const s of scenarios) {
  const rng = web.mulberry32(s.seed);
  let frame = 0;
  const calls = [];
  const frames = [];
  let done = 0;
  const p = web.createPlayer({
    state: s.state, autoStart: false, playOnMount: s.play, onDone: () => done++,
    random: () => { const v = rng(); calls.push([frame, v]); return v; },
    onFrame: svg => { frames[frame] = { ry: ovalRy(svg) }; },
  });
  frames[0] = { ...frames[0], phase: p.phase, t: p.time };
  for (const dt of s.dts) {
    frame++;
    p.advance(dt);
    // onFrame skips unchanged frames, so carry the previous eyes forward.
    frames[frame] = { ry: frames[frame]?.ry ?? frames[frame - 1].ry, phase: p.phase, t: p.time, done };
  }
  p.destroy();
  out.push({ ...s, calls, frames });
}
const file = path.join(here, '..', 'test', 'fixtures', 'web_player_trace.json');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, JSON.stringify({ note: 'Generated by tool/web-trace.mjs from the web player. Do not edit.', scenarios: out }) + '\n');
console.log(`wrote ${path.relative(process.cwd(), file)} (${out.map(s => `${s.name}: ${s.calls.length} random calls`).join(', ')})`);
